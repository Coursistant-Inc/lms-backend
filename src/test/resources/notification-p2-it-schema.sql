CREATE TABLE IF NOT EXISTS assignment_grade (
  id INT NOT NULL AUTO_INCREMENT,
  assignment_id INT NOT NULL,
  student_user_id INT NULL,
  group_id INT NULL,
  submission_version_id INT NULL,
  rubric_version_id INT NULL,
